-- Reservation / booking foundation (Part 1).
-- Extends the EXISTING `reservations` table (created in 001). No new bookings table, no data is dropped.
--
-- Adds: a unique booking reference, pickup/return TIME of day, a stored price breakdown, and a database-level
-- guard against overlapping reservations for the same car.
--
-- Existing rows are backfilled: they keep their dates and prices, get a reference, 00:00 times
-- (the UI shows a 00:00 time as "date only") and a breakdown that equals their stored total.

-- ---------------------------------------------------------------- booking reference
-- "CCS-261108-K7M2X": brand, yymmdd, 5 random characters without look-alikes (no 0/O/1/I).
-- Generated by the database so every insert path (API, seed, future modules) gets one.
-- Uniqueness is enforced by the constraint below; the API retries on the rare collision.
CREATE OR REPLACE FUNCTION generate_booking_reference() RETURNS VARCHAR AS $$
DECLARE
  alphabet CONSTANT TEXT := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  ref TEXT := 'CCS-' || to_char(NOW(), 'YYMMDD') || '-';
  i INTEGER;
BEGIN
  FOR i IN 1..5 LOOP
    ref := ref || substr(alphabet, 1 + floor(random() * length(alphabet))::INTEGER, 1);
  END LOOP;
  RETURN ref;
END;
$$ LANGUAGE plpgsql VOLATILE;

-- ---------------------------------------------------------------- new columns
ALTER TABLE reservations
  ADD COLUMN booking_reference   VARCHAR(24),
  ADD COLUMN pickup_time         TIME NOT NULL DEFAULT '00:00',
  ADD COLUMN return_time         TIME NOT NULL DEFAULT '00:00',
  ADD COLUMN rental_days         INTEGER,
  ADD COLUMN subtotal_amount     NUMERIC(12, 2),
  ADD COLUMN service_fee_amount  NUMERIC(12, 2) NOT NULL DEFAULT 0,
  ADD COLUMN tax_amount          NUMERIC(12, 2) NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------- backfill existing rows
-- Legacy reservations were priced as daily_price x (inclusive calendar days), so that is what is recorded.
UPDATE reservations SET
  booking_reference = 'CCS-' || to_char(created_at, 'YYMMDD') || '-' || lpad(id::TEXT, 5, '0'),
  rental_days       = (return_date - pickup_date) + 1,
  subtotal_amount   = total_price;

ALTER TABLE reservations
  ALTER COLUMN booking_reference SET NOT NULL,
  ALTER COLUMN booking_reference SET DEFAULT generate_booking_reference(),
  ALTER COLUMN rental_days       SET NOT NULL,
  ALTER COLUMN subtotal_amount   SET NOT NULL;

-- ---------------------------------------------------------------- constraints
ALTER TABLE reservations
  ADD CONSTRAINT reservations_booking_reference_key UNIQUE (booking_reference),
  ADD CONSTRAINT chk_reservations_rental_days CHECK (rental_days >= 1),
  ADD CONSTRAINT chk_reservations_amounts     CHECK (subtotal_amount >= 0 AND service_fee_amount >= 0 AND tax_amount >= 0),
  -- The stored total is always exactly the sum of its parts.
  ADD CONSTRAINT chk_reservations_total_matches CHECK (total_price = subtotal_amount + service_fee_amount + tax_amount);

-- Return must be strictly after pickup. NOT VALID: applies to every new/updated row but does not re-check
-- legacy rows, which only had dates (all stored at 00:00).
ALTER TABLE reservations
  ADD CONSTRAINT chk_reservations_time_order
  CHECK ((return_date + return_time) > (pickup_date + pickup_time)) NOT VALID;

-- ---------------------------------------------------------------- double-booking guard (database level)
-- The API already serialises bookings per car with a row lock. This is the second line of defence: PostgreSQL
-- itself refuses two upcoming/active reservations whose calendar days overlap for the same car. Day granularity
-- matches the availability calendar (a day with any booking is a booked day).
-- If the extension cannot be created (needs CREATE privilege) or old data already overlaps, the migration
-- continues with a WARNING instead of blocking every deploy; the row lock in the API still prevents double bookings.
DO $$
BEGIN
  CREATE EXTENSION IF NOT EXISTS btree_gist;
  ALTER TABLE reservations
    ADD CONSTRAINT reservations_no_overlap
    EXCLUDE USING gist (
      car_id WITH =,
      daterange(pickup_date, return_date, '[]') WITH &&
    ) WHERE (status IN ('upcoming', 'active'));
EXCEPTION
  WHEN insufficient_privilege THEN
    RAISE WARNING 'reservations_no_overlap NOT created: cannot create the btree_gist extension (%). API row locking still protects against double booking.', SQLERRM;
  WHEN exclusion_violation THEN
    RAISE WARNING 'reservations_no_overlap NOT created: existing reservations already overlap for the same car (%). Fix the data and add the constraint manually.', SQLERRM;
END
$$;

-- ---------------------------------------------------------------- indexes
-- (car_id, pickup_date, return_date), (status), (partner_id), (customer_id) already exist from 001.
CREATE INDEX idx_reservations_customer_created ON reservations (customer_id, created_at DESC);
CREATE INDEX idx_reservations_car_status       ON reservations (car_id, status);
